export function resolveTheme(
  preference: ThemePreference,
  systemScheme: "light" | "dark" | null | undefined,
): AppTheme {
  return themes[
    preference === "system"
      ? systemScheme === "dark"
        ? "night"
        : "olive"
      : preference
  ];
}
